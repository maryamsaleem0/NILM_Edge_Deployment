"""
timestamp_ref.py  --  reference for the 8 timestamp input channels of NILMFormer.

This is the SPEC that Person 2 ports to C. It uses only integer arithmetic on the
Unix start time of a window (seconds, UTC) and reproduces what the repo does in
NILMDataset._create_exogene (src/helpers/dataset.py) with
list_exo_variables = [minute, hour, dow, month], cosinbase=True, freq="1min".

Model input for a window of L samples = 9 channels x L:
    ch 0 : aggregate power / 6000
    ch 1,2 : sin, cos of 2*pi*minute/60      minute 0..59
    ch 3,4 : sin, cos of 2*pi*hour/24        hour   0..23
    ch 5,6 : sin, cos of 2*pi*dow/7          dow    Monday=0 .. Sunday=6 (no -1)
    ch 7,8 : sin, cos of 2*pi*month/12       month  1..12 (no -1; December -> angle 2*pi)
Sample i of the window uses t_i = start_unix + 60*i  (UTC, no time zone, no DST).

Run   python timestamp_ref.py            -> self-test against pandas (needs numpy, pandas)
      python timestamp_ref.py --emit_c   -> print a C header with the sin/cos lookup tables
"""
import sys
import numpy as np

STEP_S = 60  # sampling period in seconds (1 min)


def civil_from_days(days):
    """Days since 1970-01-01 -> (year, month 1..12, day 1..31). Valid for days >= -719468.
    Integer-only (Howard Hinnant's algorithm), so it ports directly to C."""
    z = np.asarray(days, dtype=np.int64) + 719468
    era = z // 146097
    doe = z - era * 146097                                   # [0, 146096]
    yoe = (doe - doe // 1460 + doe // 36524 - doe // 146096) // 365
    y = yoe + era * 400
    doy = doe - (365 * yoe + yoe // 4 - yoe // 100)
    mp = (5 * doy + 2) // 153
    d = doy - (153 * mp + 2) // 5 + 1
    m = np.where(mp < 10, mp + 3, mp - 9)
    y = y + (m <= 2)
    return y, m, d


def time_fields(start_unix, length, step_s=STEP_S):
    """minute, hour, dow, month arrays (int64) for each of the `length` samples."""
    t = int(start_unix) + step_s * np.arange(length, dtype=np.int64)
    minute = (t // 60) % 60
    hour = (t // 3600) % 24
    days = t // 86400
    dow = (days + 3) % 7                                      # 1970-01-01 was a Thursday (=3)
    _, month, _ = civil_from_days(days)
    return minute, hour, dow, month


def exo_channels(start_unix, length, step_s=STEP_S):
    """The 8 timestamp channels, float32, shape (8, length)."""
    minute, hour, dow, month = time_fields(start_unix, length, step_s)
    out = np.empty((8, length), dtype=np.float32)
    for k, (v, period) in enumerate([(minute, 60.0), (hour, 24.0), (dow, 7.0), (month, 12.0)]):
        out[2 * k] = np.sin(2 * np.pi * v / period)
        out[2 * k + 1] = np.cos(2 * np.pi * v / period)
    return out


def model_input(power_scaled, start_unix):
    """(9, L) model input from a scaled power window (L,) and its start time."""
    power_scaled = np.asarray(power_scaled, dtype=np.float32)
    return np.concatenate([power_scaled[None, :], exo_channels(start_unix, power_scaled.shape[0])], axis=0)


def emit_c_header():
    """Lookup tables (float32) -> C header. Index minute 0..59, hour 0..23, dow 0..6, month 1..12."""
    def table(name, n, period, first):
        vals = [(2 * np.pi * (first + i) / period) for i in range(n)]
        s = ", ".join(f"{np.float32(np.sin(a)):.9e}f" for a in vals)
        c = ", ".join(f"{np.float32(np.cos(a)):.9e}f" for a in vals)
        return f"static const float {name}_SIN[{n}] = {{ {s} }};\nstatic const float {name}_COS[{n}] = {{ {c} }};\n"
    lines = ["/* generated by timestamp_ref.py --emit_c ; index = value - first (month: index = month-1) */",
             "#define NILM_POWER_DIVISOR 6000.0f", "#define NILM_STEP_S 60", ""]
    lines.append(table("EXO_MINUTE", 60, 60.0, 0))
    lines.append(table("EXO_HOUR", 24, 24.0, 0))
    lines.append(table("EXO_DOW", 7, 7.0, 0))
    lines.append(table("EXO_MONTH", 12, 12.0, 1))
    return "\n".join(lines)


def _self_test():
    import pandas as pd
    rng = np.random.default_rng(0)
    worst = 0.0
    n = 0
    # random whole-minute start times 2012..2030, several window lengths, plus month/year/leap boundaries
    starts = [int(x) * 60 for x in rng.integers(1_350_000_000 // 60, 1_900_000_000 // 60, 400)]
    for ts in ["2012-12-31 23:50", "2016-02-28 23:30", "2016-02-29 23:59", "2017-04-30 23:00",
               "2013-02-28 23:59", "2100-02-28 23:59", "2000-02-29 12:00", "2024-12-31 23:00"]:
        starts.append(int((pd.Timestamp(ts) - pd.Timestamp(0)) // pd.Timedelta(seconds=1)))
    for L in (64, 96, 128, 256):
        for s in starts:
            tmp = pd.date_range(start=pd.to_datetime(s, unit="s"), periods=L, freq="1min")
            repo = np.zeros((8, L), np.float32)           # same formulas as NILMDataset._create_exogene
            for k, (v, p) in enumerate([(tmp.minute.values, 60.0), (tmp.hour.values, 24.0),
                                        (tmp.dayofweek.values, 7.0), (tmp.month.values, 12.0)]):
                repo[2 * k] = np.sin(2 * np.pi * v / p)
                repo[2 * k + 1] = np.cos(2 * np.pi * v / p)
            mine = exo_channels(s, L)
            worst = max(worst, float(np.abs(mine - repo).max()))
            fields = time_fields(s, L)
            for a, b in zip(fields, (tmp.minute.values, tmp.hour.values, tmp.dayofweek.values, tmp.month.values)):
                assert np.array_equal(a, b), f"field mismatch at start {s}, L {L}"
            n += 1
    print(f"self-test OK: {n} windows, max |diff| vs pandas formulas = {worst:.3e}")
    assert worst < 1e-6


if __name__ == "__main__":
    if "--emit_c" in sys.argv:
        print(emit_c_header())
    else:
        _self_test()
